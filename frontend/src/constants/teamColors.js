// Main lookup function — DO NOT hardcode colors anywhere else in the app.
// Always call this function. If the team name has slight variations (FC, 1., etc.)
// it tries multiple fallbacks before returning the default gray.
export function getTeamColor(teamName) {
  if (!teamName) return TEAM_COLORS['default'];

  // Direct match
  if (TEAM_COLORS[teamName]) return TEAM_COLORS[teamName];

  // Try stripping common prefixes/suffixes
  const stripped = teamName
    .replace(/^(FC |AFC |SC |SS |AS |AC |RC |SV |VfB |VfL |1. FC |1. FSV |TSG |SSC |CF |CD |UD |RCD |RB )/i, '')
    .replace(/( FC| CF| SC| AC| BC| CFC| AFC| United| City| Town| Calcio| 1909| Wanderers)$/i, '')
    .trim();

  if (TEAM_COLORS[stripped]) return TEAM_COLORS[stripped];

  // Partial match — find a key that contains the team name or vice versa
  const lower = teamName.toLowerCase();
  const partialKey = Object.keys(TEAM_COLORS).find(k =>
    k !== 'default' && (k.toLowerCase().includes(lower) || lower.includes(k.toLowerCase()))
  );
  if (partialKey) return TEAM_COLORS[partialKey];

  console.warn('[teamColors] No color found for:', teamName, '— add to TEAM_COLORS');
  return TEAM_COLORS['default'];
}

